<?php

namespace Lucinda\Project\Persistence\Queries;

use Lucinda\Query\Delete;
use Lucinda\Query\Insert;
use Lucinda\Query\Select;
use Lucinda\Query\Update;

/**
 * Owns one generated SQL statement and its bound parameter values
 *
 * Concrete operations construct their statement through lucinda/queries.
 * The executor receives this object rather than arbitrary SQL text.
 *
 * @internal
 */
abstract class Query
{
    /** Generated statement retained for this operation */
    protected Select|Insert|Update|Delete $statement;

    /** @var array<string, int|string|float|bool|null> Bound values by name */
    protected array $parameters = [];

    /**
     * Renders the generated statement for preparation
     *
     * @return string SQL generated by the statement library
     * @throws \Lucinda\Query\Exception If the statement is incomplete
     */
    public function getSql(): string
    {
        return (string) $this->statement;
    }

    /**
     * Gets the values bound when this operation executes
     *
     * @return array<string, int|string|float|bool|null> Named parameter values
     */
    public function getParameters(): array
    {
        return $this->parameters;
    }

    /**
     * Determines whether this operation returns selected rows
     *
     * @return bool True for a SELECT statement
     */
    public function isSelection(): bool
    {
        return $this->statement instanceof Select;
    }
}
