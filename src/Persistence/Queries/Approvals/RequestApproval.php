<?php

namespace Lucinda\Project\Persistence\Queries\Approvals;

use Lucinda\Framework\Persistence\Queries\Query;
use Lucinda\Framework\Persistence\SqlVendor;

/**
 * Records an approval request without replacing an existing decision
 *
 * Delegates SQL construction and typed bindings to the connection's dialect.
 *
 * @internal
 */
final class RequestApproval extends Query
{
    /**
     * Vendor implementation retained for this operation
     */
    private Query $wrapper;

    /**
     * Selects the vendor implementation and passes the operation inputs
     *
     * @param SqlVendor $sqlVendor Dialect of the executing connection
     * @param string $vendor Configured OAuth2 provider name
     * @param string $remote Provider-assigned identity identifier
     * @param string $name Display name supplied for the account
     * @param string $email Optional profile email address
     */
    public function __construct(
        SqlVendor $sqlVendor,
        string $vendor,
        string $remote,
        string $name,
        string $email
    ) {
        if ($sqlVendor === SqlVendor::MySQL) {
            $this->wrapper = new RequestApproval\MySQL(
                $vendor,
                $remote,
                $name,
                $email
            );
        } elseif ($sqlVendor === SqlVendor::PostgreSQL) {
            $this->wrapper = new RequestApproval\PostgreSQL(
                $vendor,
                $remote,
                $name,
                $email
            );
        } else {
            $this->wrapper = new RequestApproval\SQLite(
                $vendor,
                $remote,
                $name,
                $email
            );
        }
    }

    /**
     * Renders the statement generated by the selected vendor implementation
     *
     * @return string SQL containing named runtime placeholders
     */
    public function getSql(): string
    {
        return $this->wrapper->getSql();
    }

    /**
     * Returns the selected implementation's explicitly typed bindings
     *
     * @return array<string, array{value: mixed, type: \Lucinda\SQL\DataType}>
     */
    public function getParameters(): array
    {
        return $this->wrapper->getParameters();
    }

    /**
     * Reports whether the selected implementation returns rows
     *
     * @return bool True for a selection, false for a write
     */
    public function isSelection(): bool
    {
        return $this->wrapper->isSelection();
    }
}
